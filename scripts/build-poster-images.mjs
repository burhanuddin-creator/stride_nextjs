// Builds the Home "Coming Soon to Westmont" poster images from the original (kept unchanged in brand-assets/).
//
// Runs automatically before every `npm run build` (package.json "prebuild"), so replacing the PNG is all a poster update
// needs. It regenerates only when the PNG's SHA-256 differs from the one recorded in the manifest (or an output file is
// missing); `--force` regenerates regardless. Manual run:
//   node scripts/build-poster-images.mjs && node scripts/build-image-imports.mjs
//
// Output: src/assets/images/home/<id>.webp (native width) + <id>-480/800/1200.webp, and
// src/data/generated/posterMediaManifest.ts. No filter or retouching; never upscaled.
//   coming-soon-westmont-poster  the whole poster (desktop hero slide), resize only
//   coming-soon-westmont-photo   the text-free photo on the poster's right (x ≥ 1150), the mobile slide's background
//
// The images are imported statically, so Next.js serves them under content-hashed URLs (/_next/static/media/…): new
// pixels always get a new URL, and no browser or CDN can keep serving the old poster.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'src', 'assets', 'images', 'home');
const manifestFile = path.join(root, 'src', 'data', 'generated', 'posterMediaManifest.ts');
const POSTER = path.join(root, 'brand-assets', 'posters', 'coming-soon-westmont.png');
const PHOTO_LEFT = 1150; // where the poster's text column ends and the clinic photo begins
const WIDTHS = [480, 800, 1200];
const QUALITY = 84; // the poster carries text, so a little more quality than the scene photos

const sourceSha256 = crypto.createHash('sha256').update(fs.readFileSync(POSTER)).digest('hex');
const { width: posterWidth, height: posterHeight } = await sharp(POSTER).metadata();
const SOURCES = {
  'coming-soon-westmont-poster': { width: posterWidth, height: posterHeight },
  'coming-soon-westmont-photo': {
    crop: { left: PHOTO_LEFT, top: 0, width: posterWidth - PHOTO_LEFT, height: posterHeight },
    width: posterWidth - PHOTO_LEFT,
    height: posterHeight,
  },
};
const outputs = (id, width) => [`${id}.webp`, ...WIDTHS.filter((w) => w < width).map((w) => `${id}-${w}.webp`)];

const previous = fs.existsSync(manifestFile) ? fs.readFileSync(manifestFile, 'utf8') : '';
const upToDate =
  previous.includes(`"sourceSha256": "${sourceSha256}"`) &&
  Object.entries(SOURCES).every(([id, { width }]) => outputs(id, width).every((f) => fs.existsSync(path.join(outDir, f))));
if (upToDate && !process.argv.includes('--force')) {
  console.log(`poster images up to date (${path.relative(root, POSTER)} sha256 ${sourceSha256.slice(0, 12)})`);
  process.exit(0);
}

const manifest = {};
for (const [id, { crop, width, height }] of Object.entries(SOURCES)) {
  const source = () => (crop ? sharp(POSTER).extract(crop) : sharp(POSTER));
  // Remove outputs of a previous, larger set of widths so no stale variant is left behind.
  for (const f of fs.readdirSync(outDir).filter((f) => f === `${id}.webp` || new RegExp(`^${id}-\\d+\\.webp$`).test(f))) {
    fs.rmSync(path.join(outDir, f));
  }
  await source().webp({ quality: QUALITY }).toFile(path.join(outDir, `${id}.webp`));
  const widths = WIDTHS.filter((w) => w < width);
  for (const w of widths) await source().resize({ width: w }).webp({ quality: QUALITY }).toFile(path.join(outDir, `${id}-${w}.webp`));
  manifest[id] = { format: 'webp', width, height, widths };
  console.log(`${id}: ${width}×${height}, widths ${widths.join(', ')}`);
}
fs.writeFileSync(
  manifestFile,
  `// GENERATED by scripts/build-poster-images.mjs — do not edit by hand.\n` +
    `// Source: brand-assets/posters/coming-soon-westmont.png\n` +
    `export const POSTER_SOURCE = { "sourceSha256": "${sourceSha256}" } as const;\n` +
    `export const POSTER_MEDIA_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n`,
);
