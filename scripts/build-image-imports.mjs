// Writes src/data/generated/imageFiles.ts: one static import per file in src/assets/images/{site,home}.
// Replaces Vite's import.meta.glob (src/data/media.ts). Static imports let Next.js fingerprint each image under
// /_next/static/media/ (long-term cacheable), exactly like the hashed Vite assets. Re-run after adding images:
//   node scripts/build-image-imports.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src/data/generated/imageFiles.ts');
const lines = ['// GENERATED by scripts/build-image-imports.mjs — do not edit by hand.', "import type { StaticImageData } from 'next/image';"];
const entries = { site: [], home: [] };
let n = 0;
for (const folder of ['site', 'home']) {
  const dir = path.join(root, 'src/assets/images', folder);
  for (const name of fs.readdirSync(dir).filter((f) => /\.(webp|svg|png|jpe?g)$/.test(f)).sort()) {
    const id = `img${n++}`;
    lines.push(`import ${id} from '../../assets/images/${folder}/${name}';`);
    entries[folder].push(`  '${name}': ${id},`);
  }
}
lines.push('', 'export const SITE_FILES: Record<string, StaticImageData> = {', ...entries.site, '};');
lines.push('', 'export const HOME_FILES: Record<string, StaticImageData> = {', ...entries.home, '};', '');
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${path.relative(root, out)} (${n} images)`);
